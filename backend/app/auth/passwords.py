import hashlib
import hmac
import secrets

SCRYPT_N = 2**14
SCRYPT_R = 8
SCRYPT_P = 1
KEY_LENGTH = 32


def hash_password(password: str) -> str:
    if len(password) < 12:
        raise ValueError("Password must be at least 12 characters")

    salt = secrets.token_bytes(16)
    derived_key = hashlib.scrypt(
        password.encode("utf-8"),
        salt=salt,
        n=SCRYPT_N,
        r=SCRYPT_R,
        p=SCRYPT_P,
        dklen=KEY_LENGTH,
    )

    return f"scrypt${SCRYPT_N}${SCRYPT_R}${SCRYPT_P}${salt.hex()}${derived_key.hex()}"


def verify_password(password: str, stored_hash: str) -> bool:

    try:
        algorithm, n, r, p, salt_hex, key_hex = stored_hash.split("$")

        if algorithm != "scrypt":
            return False

        # Only accept parameters generated by this application.
        if (int(n), int(r), int(p)) != (
            SCRYPT_N,
            SCRYPT_R,
            SCRYPT_P,
        ):
            return False

        salt = bytes.fromhex(salt_hex)
        expected = bytes.fromhex(key_hex)

        if len(salt) != 16 or len(expected) != KEY_LENGTH:
            return False

        actual = hashlib.scrypt(
            password.encode("utf-8"),
            salt=salt,
            n=SCRYPT_N,
            r=SCRYPT_R,
            p=SCRYPT_P,
            dklen=KEY_LENGTH,
        )

        return hmac.compare_digest(actual, expected)

    except (ValueError, TypeError, OverflowError):
        return False
